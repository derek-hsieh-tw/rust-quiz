fn main() {
    println!("Hello, world!");

    pre();
}

fn pre(){
    // ==================================================
    //   Rust 變數預設型別與核心推導規則 (Cheatsheet)
    // ==================================================

    // 一、預設原生型別 (無上下文時的預設值)
    // --------------------------------------------------

    // 整數 (Integer) -> i32
    let x = 10;

    // 浮點數 (Float) -> f64
    let x = 3.14;

    // 字元 (Char) -> char (4-byte UTF-8)
    let c = 'A';

    // 布林值 (Boolean) -> bool
    let is_active = true;

    // 字串字面值 (String) -> &'static str
    let s = "hello";

    // 陣列 (Array) -> [T; N] (依內容推導，如 [i32; 3])
    let arr = [1, 2, 3];

    // 元組 (Tuple) -> (T1, T2, ...) (依內容推導，如 (i32, f64))
    let t = (1, 3.14);

    // 二、何時「必須標註型別」
    // --------------------------------------------------

    // 1. 函式簽名 (強制的！)
    fn add(a: i32, b: i32) -> i32 {
        a + b
    }

    // 2. Struct / Enum 的欄位定義 (強制的！)
    struct User {
        name: String,
        age: u32,
    }

    // 3. 缺乏上下文且無法自動推導時 (如 parse)
    fn parse_example() {
        let num = "42".parse::<i32>().unwrap();
        // 或：let num: i32 = "42".parse().unwrap();
    }

    // 三、C# 轉 Rust 的型別心法
    // --------------------------------------------------
    // 1. 區域變數 (let) 儘管放手不寫，Rust 沒有隱式轉型，
    //    編譯器會根據後續程式碼 100% 嚴格鎖定型別。
    // 2. 只有在需要明確限制記憶體大小 (如 u8, f32) 時，
    //    才需要手動宣告區域變數型別。
}
